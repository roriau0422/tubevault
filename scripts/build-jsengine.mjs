// Bundles src/jsengine/harness.ts (+ bgutils-js) into a single IIFE that runs
// inside the hidden WebView. Regenerate after changing the harness or bumping
// bgutils-js:  node scripts/build-jsengine.mjs
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: ['src/jsengine/harness.ts'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'safari15',
  write: false,
  minify: true,
  legalComments: 'none',
});

const code = result.outputFiles[0].text;
// Emit as a TS module exporting the bundle string so Metro inlines it (no asset IO).
const out = `// AUTO-GENERATED by scripts/build-jsengine.mjs — do not edit.\n/* eslint-disable */\nexport const JS_ENGINE_BUNDLE = ${JSON.stringify(code)};\n`;
writeFileSync('src/jsengine/bundle.ts', out);
console.log(`wrote src/jsengine/bundle.ts (${(code.length / 1024).toFixed(1)} KB)`);
